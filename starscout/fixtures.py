def _build() -> list[dict[str, Any]]:
    from .rank import quality_score

    out: list[dict[str, Any]] = []
    for full_name, lang, stars, forks, created, pushed, lic, topics, desc in DEMO:
        owner, name = full_name.split("/", 1)
        rec = {
            "full_name": full_name,
            "owner": owner,
            "name": name,
            "description": desc,
            "language": lang,
            "topics": topics,
            "stars": stars,
            "forks": forks,
            "open_issues": max(1, forks // 20),
            "created_at": f"{created}T00:00:00Z",
            "pushed_at": f"{pushed}T00:00:00Z",
            "license": lic,
            "archived": False,
            "homepage": None,
            "source": "demo",
        }
        rec["quality"] = quality_score(rec)
        out.append(rec)
    return out


def load() -> list[dict[str, Any]]:
    return _build()
